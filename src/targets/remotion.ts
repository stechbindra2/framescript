import {mkdir, writeFile} from 'node:fs/promises';
import path from 'node:path';
import type {TimelineIR} from '../ir.js';
import type {FrameScriptPlugin, RemotionPluginLayer} from '../plugins.js';
import type {FrameScriptSourceMap} from '../source-map.js';
import type {MediaProbeReport} from '../media.js';

const REMOTION_VERSION = '4.0.533';

export interface RemotionProjectOptions {
  readonly outputDirectory: string;
  readonly projectName?: string;
  readonly plugins?: readonly FrameScriptPlugin[];
  readonly sourceMap?: FrameScriptSourceMap;
  readonly mediaManifest?: MediaProbeReport;
}

export interface GeneratedProject {
  readonly directory: string;
  readonly files: readonly string[];
}

export async function generateRemotionProject(
  ir: TimelineIR,
  options: RemotionProjectOptions,
): Promise<GeneratedProject> {
  const directory = path.resolve(options.outputDirectory);
  const sourceDirectory = path.join(directory, 'src');
  const publicDirectory = path.join(directory, 'public');
  await mkdir(sourceDirectory, {recursive: true});
  await mkdir(publicDirectory, {recursive: true});

  const pluginLayers = collectPluginLayers(ir, options.plugins ?? []);
  const sourceMap = options.sourceMap ?? emptySourceMap();
  const files = new Map<string, string>([
    ['package.json', projectPackage(options.projectName ?? 'framescript-video', pluginLayers)],
    ['tsconfig.json', projectTsconfig()],
    ['remotion.config.ts', remotionConfig()],
    ['src/program.generated.ts', generatedProgram(ir)],
    ['framescript.map.json', `${JSON.stringify(sourceMap, null, 2)}\n`],
    ['media-manifest.json', `${JSON.stringify(options.mediaManifest ?? emptyMediaManifest(), null, 2)}\n`],
    ['src/source-map.generated.ts', generatedSourceMap(sourceMap)],
    ['src/fonts.generated.ts', generatedFonts(ir)],
    ['src/FrameScriptRuntimeBoundary.tsx', runtimeBoundarySource()],
    ['src/FrameScriptComposition.tsx', runtimeSource(pluginLayers)],
    ['src/Root.tsx', rootSource()],
    ['src/index.ts', entrySource()],
    ['README.md', generatedReadme()],
  ]);

  await Promise.all([...files].map(async ([relative, contents]) => {
    const destination = path.join(directory, relative);
    await mkdir(path.dirname(destination), {recursive: true});
    await writeFile(destination, contents, 'utf8');
  }));
  return {directory, files: [...files.keys()]};
}

function projectPackage(name: string, pluginLayers: ReadonlyMap<string, RemotionPluginLayer>): string {
  const pluginDependencies = Object.fromEntries(
    [...pluginLayers.values()].map(({packageName, packageVersion}) => [packageName, packageVersion]),
  );
  return `${JSON.stringify({
    name: sanitizePackageName(name),
    version: '0.0.0',
    private: true,
    type: 'module',
    scripts: {
      studio: 'remotion studio src/index.ts',
      render: 'remotion render src/index.ts',
      still: 'remotion still src/index.ts',
      check: 'tsc --noEmit',
    },
    dependencies: {
      '@remotion/cli': REMOTION_VERSION,
      '@remotion/fonts': REMOTION_VERSION,
      '@remotion/media': REMOTION_VERSION,
      remotion: REMOTION_VERSION,
      react: '19.2.0',
      'react-dom': '19.2.0',
      ...pluginDependencies,
    },
    devDependencies: {
      '@types/react': '19.2.2',
      '@types/react-dom': '19.2.2',
      typescript: '5.9.3',
    },
  }, null, 2)}\n`;
}


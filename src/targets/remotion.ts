function generatedProgram(ir: TimelineIR): string {
  return `// Generated by FrameScript. Do not edit by hand.\nexport default ${JSON.stringify(ir, null, 2)} as const;\n`;
}

function generatedSourceMap(sourceMap: FrameScriptSourceMap): string {
  return `// Generated by FrameScript. Do not edit by hand.\nexport default ${JSON.stringify(sourceMap, null, 2)} as const;\n`;
}

function runtimeBoundarySource(): string {
  return `import {Component, type ErrorInfo, type ReactNode} from 'react';

export type FrameScriptSourceMap = {
  readonly sources: readonly {readonly id: string; readonly path: string}[];
  readonly mappings: Readonly<Record<string, {
    readonly source: string;
    readonly start: {readonly line: number; readonly column: number};
  }>>;
};

const sourceLocation = (sourceMap: FrameScriptSourceMap, key: string): string | undefined => {
  let candidate = key;
  while (candidate.length > 0) {
    const mapping = sourceMap.mappings[candidate];
    const source = mapping ? sourceMap.sources.find(({id}) => id === mapping.source) : undefined;
    if (mapping && source) return \`\${source.path}:\${mapping.start.line}:\${mapping.start.column}\`;
    const separator = candidate.lastIndexOf('/');
    if (separator < 0) break;
    candidate = candidate.slice(0, separator);
  }
  return undefined;
};

export const remapFrameScriptError = (error: unknown, sourceKey: string, sourceMap: FrameScriptSourceMap): Error => {
  const original = error instanceof Error ? error : new Error(String(error));
  if (original.name === 'FrameScriptRuntimeError') return original;
  const location = sourceLocation(sourceMap, sourceKey);
  const suffix = location ? \`\\nFrameScript source: \${location} [\${sourceKey}]\` : \`\\nFrameScript source key: \${sourceKey}\`;
  const remapped = new Error(\`\${original.message}\${suffix}\`, {cause: original});
  remapped.name = 'FrameScriptRuntimeError';
  return remapped;
};

type Props = {
  readonly sourceKey: string;
  readonly sourceMap: FrameScriptSourceMap;
  readonly children: ReactNode;
};
type State = {readonly error?: unknown};

export class FrameScriptRuntimeBoundary extends Component<Props, State> {
  public override state: State = {};

  public static getDerivedStateFromError(error: unknown): State {
    return {error};
  }

  public override componentDidCatch(_error: unknown, _info: ErrorInfo): void {
    // The next render rethrows a source-enriched error to Remotion's renderer.
  }

  public override render(): ReactNode {
    if (this.state.error !== undefined) {
      throw remapFrameScriptError(this.state.error, this.props.sourceKey, this.props.sourceMap);
    }
    return this.props.children;
  }
}
`;
}

function generatedFonts(ir: TimelineIR): string {
  if (ir.fonts.length === 0) return '// Generated by FrameScript. No declared fonts.\n';
  const entries = ir.fonts.map((font) => {
    const source = resolveDeclaredSource(font.source, ir);
    const url = /^(?:https?:|data:|blob:)/u.test(source) ? JSON.stringify(source) : `staticFile(${JSON.stringify(source)})`;
    return `loadFont({family: ${JSON.stringify(font.family)}, url: ${url}, weight: ${JSON.stringify(String(font.weight))}, style: ${JSON.stringify(font.style)}});`;
  });
  return `// Generated by FrameScript. Do not edit by hand.
import {loadFont} from '@remotion/fonts';
import {staticFile} from 'remotion';

${entries.join('\n')}
`;
}

